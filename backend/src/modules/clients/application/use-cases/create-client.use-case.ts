import {
  ConflictError,
  ValidationError,
} from '../../../../shared/domain/errors/index.js';
import { Client, NIT_PATTERN } from '../../domain/entities/client.js';
import type { ClientRepository } from '../../domain/repositories/client.repository.js';
import { assertCatalogsExist } from '../catalog-validation.js';
import type { ActivityLogPort } from '../ports/activity-log.port.js';
import type { CatalogValidatorPort } from '../ports/catalog-validator.port.js';
import type { ClientActor } from '../types/client-actor.js';

export interface CreateClientInput {
  actor: ClientActor;
  nit: string;
  businessName: string;
  tradeName?: string | null;
  address?: string | null;
  department?: string | null;
  municipality?: string | null;
  neighborhood?: string | null;
  phone?: string | null;
  email?: string | null;
  zoneId?: number | null;
  clientTypeId?: number | null;
  clientPotentialId?: number | null;
  clientStatusId?: number | null;
  visitFrequencyDays?: number | null;
  latitude?: number | null;
  longitude?: number | null;
}

export class CreateClientUseCase {
  constructor(
    private readonly clients: ClientRepository,
    private readonly catalogs: CatalogValidatorPort,
    private readonly activityLog: ActivityLogPort,
  ) {}

  async execute(input: CreateClientInput): Promise<Client> {
    if (!input.nit || !input.businessName) {
      throw new ValidationError('nit and businessName are required');
    }
    const nit = input.nit.trim();
    const businessName = input.businessName.trim();
    if (!nit || !businessName) {
      throw new ValidationError('nit and businessName are required');
    }
    if (!NIT_PATTERN.test(nit)) {
      throw new ValidationError(
        'nit must be a valid Colombian NIT: 9 to 10 digits with an optional hyphen',
      );
    }

    // The NIT is unique across the system (409 on duplicates).
    if (await this.clients.findByNit(nit)) {
      throw new ConflictError('A client with the same NIT already exists');
    }

    await assertCatalogsExist(this.catalogs, {
      zone: input.zoneId,
      client_type: input.clientTypeId,
      client_potential: input.clientPotentialId,
      client_status: input.clientStatusId,
    });

    const client = await this.clients.save(
      new Client({
        id: null,
        nit,
        businessName,
        tradeName: input.tradeName ?? null,
        address: input.address ?? null,
        department: input.department ?? null,
        municipality: input.municipality ?? null,
        neighborhood: input.neighborhood ?? null,
        phone: input.phone ?? null,
        email: input.email ?? null,
        zoneId: input.zoneId ?? null,
        clientTypeId: input.clientTypeId ?? null,
        clientPotentialId: input.clientPotentialId ?? null,
        clientStatusId: input.clientStatusId ?? null,
        visitFrequencyDays: input.visitFrequencyDays ?? null,
        latitude: input.latitude ?? null,
        longitude: input.longitude ?? null,
        active: true,
        createdAt: null,
        updatedAt: null,
      }),
    );

    await this.activityLog.record({
      action: 'client.created',
      userId: input.actor.id,
      // save() persists the id generated by the database.
      clientId: client.id!,
      description: `Client '${client.businessName}' (NIT ${client.nit}) created`,
      occurredAt: new Date(),
    });

    return client;
  }
}
